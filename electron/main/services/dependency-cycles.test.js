const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')

test('Python cycle checks follow package-member and parent-package imports', async context => {
  const { pythonGraph, findCycles } = await import('../../../scripts/check-dependency-cycles.mjs')
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'rms-dependency-graph-'))
  context.after(() => fs.rm(directory, { recursive: true, force: true }))
  await fs.mkdir(path.join(directory, 'records'))
  await fs.writeFile(path.join(directory, '__init__.py'), '')
  await fs.writeFile(path.join(directory, 'service.py'), 'from .records import session as record_session\n')
  await fs.writeFile(path.join(directory, 'records', '__init__.py'), '')
  await fs.writeFile(path.join(directory, 'records', 'session.py'), 'from .. import service\n')
  const graph = pythonGraph(directory)
  assert.ok(graph.get(path.join(directory, 'service.py')).has(path.join(directory, 'records', 'session.py')))
  assert.equal(findCycles(graph).length, 1)
})
